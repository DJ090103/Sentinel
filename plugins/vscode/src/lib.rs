//! Sentinel's editor plugins: VS Code, Cursor, Kiro and Antigravity.
//!
//! (The crate is still named for VS Code, which was the first of them. Renaming
//! it would churn every dependent for no gain — the crate docs are the honest
//! record of what it covers.)
//!
//! # Why several plugins live in one crate
//!
//! Cursor, Kiro and Antigravity are all forks of VS Code, and their
//! application-data directories have the same layout, name for name — verified
//! on a real machine, not assumed. The list below decides what is safe to
//! delete out of a directory that also contains the user's settings, snippets
//! and unsaved work — so keeping **one** copy of it matters more than the
//! tidiness of one crate per plugin. Four crates would be four lists, and four
//! lists drift.
//!
//! They remain four plugins: separate ids, separate rows in the UI, separate
//! entries in cleanup history.
//!
//! # The risk here is different from a package manager
//!
//! npm's cache directory contains only cache. An editor's application-data
//! directory contains cache *next to* the things you would be most upset to
//! lose, under sibling names of similar shape. So this plugin's closed list is
//! drawn tightly, and the reasoning for each exclusion is written down below
//! rather than left implicit.
//!
//! Measured on the development machine, what is deliberately **not** offered:
//!
//! - `User/` (157 MB in VS Code, 587 MB in Cursor, 329 MB in Kiro) —
//!   `settings.json`, keybindings, snippets, `globalStorage`,
//!   `workspaceStorage`, and `History`. This is the user's configuration and
//!   per-workspace state.
//! - `snapshots/` (**1.2 GB in Cursor**, the single largest directory on this
//!   machine) — Cursor's record of previous states of your files. It is how it
//!   restores earlier versions. It is the user's work, not a cache, and it is
//!   excluded precisely *because* it is the biggest thing there.
//! - `Backups/` — editor buffers not yet written to disk. Deleting this loses
//!   unsaved work.
//! - `Partitions/`, `WebStorage/`, `Local Storage/`, `Session Storage/`,
//!   `IndexedDB/`, `Service Worker/` — web storage for webviews and
//!   extensions. Named like caches, but extensions keep durable state here.
//! - `Cookies`, `Local State`, `Preferences`, `machineid` — session and
//!   identity, not space worth reclaiming.
//!
//! The closed-list rule makes those exclusions sufficient: absence from
//! [`KNOWN_CACHES`] means there is no path by which this plugin can reach them.

use std::path::PathBuf;

use sentinel_plugin_api::{
    directory_size, is_empty_directory, validate_tool_directory, CleanFailure, CleanOutcome,
    CleanTarget, Plugin, PluginError, PluginMetadata, Recommendation, ScanResult, TargetRisk,
    VerifiedTarget,
};

