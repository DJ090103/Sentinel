/// One directory this plugin knows how to reclaim.
struct KnownCache {
    /// Directory name directly under the editor's application-data directory.
    name: &'static str,
    /// What the user sees.
    label: &'static str,
    /// How much care removing it needs.
    risk: TargetRisk,
    /// Why it is safe, or what is lost.
    note: &'static str,
}

