/// Which editor a plugin instance manages.
///
/// The two share a layout, so they share everything except identity and the
/// directory they live in.
#[derive(Debug, Clone, Copy)]
struct Editor {
    /// Stable plugin id. Permanent once shipped — cleanup history is keyed on it.
    id: &'static str,
    /// Human-readable name.
    name: &'static str,
    /// One line for the UI.
    description: &'static str,
    /// Directory name under the platform's application-data location.
    directory: &'static str,
}

const VSCODE: Editor = Editor {
    id: "vscode",
    name: "VS Code",
    description: "Caches VS Code keeps beside its settings — never the settings themselves.",
    directory: "Code",
};

const CURSOR: Editor = Editor {
    id: "cursor",
    name: "Cursor",
    description: "Caches Cursor keeps beside its settings — never your settings or file history.",
    directory: "Cursor",
};

const KIRO: Editor = Editor {
    id: "kiro",
    name: "Kiro",
    description: "Caches and logs Kiro keeps beside its settings — never the settings themselves.",
    directory: "Kiro",
};

const ANTIGRAVITY: Editor = Editor {
    id: "antigravity",
    name: "Antigravity",
    description: "Caches Antigravity keeps beside its settings — never the settings themselves.",
    directory: "Antigravity",
};

/// Shared implementation. Both plugins are this, with a different [`Editor`].
#[derive(Debug)]
struct EditorPlugin {
    editor: Editor,
    /// Overrides discovery. Exists for tests, which must never touch the
    /// developer's real editor data.
    app_data_override: Option<PathBuf>,
}

impl EditorPlugin {
    fn app_data(&self) -> Result<PathBuf, PluginError> {
        match &self.app_data_override {
            Some(path) => validate_tool_directory(path).map(|()| path.clone()),
            None => app_data::resolve(self.editor.directory),
        }
    }

    fn scan_caches(&self) -> Result<ScanResult, PluginError> {
        let root = self.app_data()?;

        let mut targets = Vec::new();
        for known in KNOWN_CACHES {
            // A constant joined onto a validated root. This is the only place a
            // path is constructed, and nothing in it is variable.
            let path = root.join(known.name);

            // `symlink_metadata` so a symlink is seen as a symlink rather than
            // as whatever it points at.
            let Ok(metadata) = std::fs::symlink_metadata(&path) else {
                continue;
            };
            if !metadata.is_dir() {
                continue;
            }

            if is_empty_directory(&path) {
                // Nothing in it, so nothing to reclaim — which is a different
                // question from measuring zero. See `is_empty_directory`.
                continue;
            }
            let size = directory_size(&path)?;

            targets.push(CleanTarget::new(
                self.editor.id,
                path,
                format!("{} — {}", known.label, known.note),
                size,
                known.risk,
            ));
        }

        Ok(ScanResult { targets })
    }
}

impl Plugin for EditorPlugin {
    fn metadata(&self) -> PluginMetadata {
        PluginMetadata {
            id: self.editor.id,
            name: self.editor.name,
            description: self.editor.description,
        }
    }

    fn scan(&self) -> Result<ScanResult, PluginError> {
        self.scan_caches()
    }

    fn recommend(&self) -> Result<Vec<Recommendation>, PluginError> {
        let scan = self.scan()?;
        if scan.targets.is_empty() {
            return Ok(Vec::new());
        }

        let mut recommendations = Vec::new();

        for risk in [TargetRisk::Safe, TargetRisk::Review] {
            let bytes = scan
                .targets
                .iter()
                .filter(|target| target.risk == risk)
                .fold(0u64, |sum, target| sum.saturating_add(target.size_bytes));

            if bytes == 0 {
                continue;
            }

            recommendations.push(match risk {
                TargetRisk::Safe => Recommendation {
                    title: format!(
                        "{} caches are using {}",
                        self.editor.name,
                        human_bytes(bytes)
                    ),
                    detail: "Compiled scripts, downloaded extension packages and web content. \
                             The editor rebuilds all of it; the next launch or two are slightly \
                             slower. Your settings, snippets and file history are not included."
                        .to_owned(),
                    reclaimable_bytes: bytes,
                    risk,
                },
                _ => Recommendation {
                    title: format!(
                        "{} logs and crash reports are using {}",
                        self.editor.name,
                        human_bytes(bytes)
                    ),
                    detail: "Records of past sessions and crashes. Safe to remove unless you're \
                             diagnosing something — unlike the caches, these can't be recreated."
                        .to_owned(),
                    reclaimable_bytes: bytes,
                    risk,
                },
            });
        }

        Ok(recommendations)
    }

    fn remove_verified(
        &self,
        verified: &[VerifiedTarget<'_>],
    ) -> Result<CleanOutcome, PluginError> {
        let mut outcome = CleanOutcome::default();

        for target in verified {
            // Measured before removal, so this reports what was actually freed
            // rather than the scan-time estimate.
            let freed = directory_size(target.path()).unwrap_or(0);

            match std::fs::remove_dir_all(target.path()) {
                Ok(()) => {
                    outcome.removed.push(target.label().to_owned());
                    outcome.reclaimed_bytes = outcome.reclaimed_bytes.saturating_add(freed);
                }
                Err(cause) => outcome.failures.push(CleanFailure {
                    label: target.label().to_owned(),
                    reason: cause.to_string(),
                }),
            }
        }

        Ok(outcome)
    }
}

/// Reclaims VS Code's caches, and nothing else in its application-data
/// directory.
#[derive(Debug)]
pub struct VsCodePlugin(EditorPlugin);

/// Reclaims Cursor's caches. Notably **not** its `snapshots` directory, which
/// holds your files' edit history — see the crate docs.
#[derive(Debug)]
pub struct CursorPlugin(EditorPlugin);

/// Reclaims Kiro's caches. Its `logs` directory is usually the largest thing
/// here and is offered as [`TargetRisk::Review`], not pre-selected.
#[derive(Debug)]
pub struct KiroPlugin(EditorPlugin);

/// Reclaims Antigravity's caches, on the same terms as the other VS Code forks.
#[derive(Debug)]
pub struct AntigravityPlugin(EditorPlugin);

macro_rules! editor_plugin {
    ($outer:ident, $editor:expr, $id:literal) => {
        impl $outer {
            /// The plugin as it ships: finds the editor's data directory itself.
            pub fn new() -> Self {
                Self(EditorPlugin {
                    editor: $editor,
                    app_data_override: None,
                })
            }

            /// A plugin pinned to a specific application-data directory, for
            /// tests.
            pub fn with_app_data(path: impl Into<PathBuf>) -> Self {
                Self(EditorPlugin {
                    editor: $editor,
                    app_data_override: Some(path.into()),
                })
            }

            /// This plugin's stable id.
            pub const fn plugin_id() -> &'static str {
                $id
            }
        }

        impl Default for $outer {
            fn default() -> Self {
                Self::new()
            }
        }

        impl Plugin for $outer {
            fn metadata(&self) -> PluginMetadata {
                self.0.metadata()
            }

            fn scan(&self) -> Result<ScanResult, PluginError> {
                self.0.scan()
            }

            fn recommend(&self) -> Result<Vec<Recommendation>, PluginError> {
                self.0.recommend()
            }

            fn remove_verified(
                &self,
                verified: &[VerifiedTarget<'_>],
            ) -> Result<CleanOutcome, PluginError> {
                self.0.remove_verified(verified)
            }
        }
    };
}

editor_plugin!(VsCodePlugin, VSCODE, "vscode");
editor_plugin!(CursorPlugin, CURSOR, "cursor");
editor_plugin!(KiroPlugin, KIRO, "kiro");
editor_plugin!(AntigravityPlugin, ANTIGRAVITY, "antigravity");

/// Formats bytes in binary units, so the figure matches `du`.
fn human_bytes(bytes: u64) -> String {
    const UNITS: [&str; 5] = ["B", "KiB", "MiB", "GiB", "TiB"];

    let mut value = bytes as f64;
    let mut unit = 0;
    while value >= 1024.0 && unit < UNITS.len() - 1 {
        value /= 1024.0;
        unit += 1;
    }

    if unit == 0 {
        format!("{bytes} {}", UNITS[0])
    } else {
        format!("{value:.1} {}", UNITS[unit])
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use sentinel_plugin_api::clean;
    use std::fs;

    /// Everything an editor's application-data directory holds that this
    /// plugin must never touch, as observed on a real machine.
    const MUST_NEVER_TOUCH: &[&str] = &[
        "User",
        "snapshots",
        "Backups",
        "Partitions",
        "WebStorage",
        "Local Storage",
        "Session Storage",
        "IndexedDB",
        "Service Worker",
        "Dictionaries",
        "blob_storage",
    ];

    fn fake_app_data(entries: &[(&str, usize)]) -> tempfile::TempDir {
        let dir = tempfile::tempdir().expect("temp dir");
        for (name, size) in entries {
            let path = dir.path().join(name);
            fs::create_dir_all(&path).expect("create directory");
            fs::write(path.join("blob"), vec![b'x'; *size]).expect("write blob");
        }
        dir
    }

    /// Every editor this crate ships, all pointed at one fixture directory.
    ///
    /// Boxed because the four are distinct types: the properties below have to
    /// hold for all of them, and a test that covered only the first two would
    /// pass while a newly added fork quietly proposed someone's settings.
    fn all_editors(app_data: &std::path::Path) -> Vec<Box<dyn Plugin>> {
        vec![
            Box::new(VsCodePlugin::with_app_data(app_data)),
            Box::new(CursorPlugin::with_app_data(app_data)),
            Box::new(KiroPlugin::with_app_data(app_data)),
            Box::new(AntigravityPlugin::with_app_data(app_data)),
        ]
    }

    #[test]
    fn every_editor_is_a_distinct_plugin() {
        let ids: Vec<_> = [
            VsCodePlugin::new().metadata().id,
            CursorPlugin::new().metadata().id,
            KiroPlugin::new().metadata().id,
            AntigravityPlugin::new().metadata().id,
        ]
        .to_vec();

        assert_eq!(ids, vec!["vscode", "cursor", "kiro", "antigravity"]);

        let unique: std::collections::HashSet<_> = ids.iter().collect();
        assert_eq!(
            unique.len(),
            ids.len(),
            "ids key cleanup history, so a collision would misattribute it"
        );
    }

    #[test]
    fn scan_reports_known_caches_with_their_sizes() {
        let data = fake_app_data(&[("Cache", 300), ("CachedData", 200)]);
        let plugin = VsCodePlugin::with_app_data(data.path());

        let scan = plugin.scan().expect("scan succeeds");

        assert_eq!(scan.targets.len(), 2);
        assert!(
            scan.total_bytes() >= 500,
            "500 bytes were written, and allocated size rounds up to whole blocks"
        );
        assert!(scan.targets.iter().all(|t| t.plugin_id() == "vscode"));
    }

    /// The property this whole plugin turns on. Settings, snippets, unsaved
    /// buffers and Cursor's file-history snapshots sit as siblings of the
    /// caches, and none of them may ever be proposed.
    #[test]
    fn nothing_the_user_would_miss_is_ever_proposed() {
        let mut entries: Vec<(&str, usize)> = MUST_NEVER_TOUCH
            .iter()
            .map(|name| (*name, 10_000_usize))
            .collect();
        entries.push(("Cache", 10));

        let data = fake_app_data(&entries);

        for plugin in all_editors(data.path()) {
            let id = plugin.metadata().id;
            let scan = plugin.scan().expect("scan succeeds");

            assert_eq!(
                scan.targets.len(),
                1,
                "only the cache should be offered, but `{id}` offered {:?}",
                scan.targets
            );

            for forbidden in MUST_NEVER_TOUCH {
                assert!(
                    scan.targets.iter().all(|t| !t.path().ends_with(forbidden)),
                    "`{forbidden}` must never be proposed, but `{id}` proposed it"
                );
            }
        }
    }

    /// Cursor's `snapshots` is the largest directory in its data folder and is
    /// the user's edit history. Being large is exactly why it needs its own
    /// test.
    #[test]
    fn cursors_file_history_survives_a_clean() {
        let data = fake_app_data(&[("snapshots", 1_000_000), ("Cache", 100)]);
        let plugin = CursorPlugin::with_app_data(data.path());

        let scan = plugin.scan().expect("scan succeeds");
        let outcome = clean(&plugin, &scan.targets).expect("clean succeeds");

        assert!(
            outcome.reclaimed_bytes >= 100,
            "100 bytes were written, and allocated size rounds up to whole blocks"
        );
        assert!(
            data.path().join("snapshots").join("blob").exists(),
            "Cursor's file history must survive"
        );
        assert!(!data.path().join("Cache").exists());
    }

    #[test]
    fn logs_and_crash_reports_are_review_not_safe() {
        let data = fake_app_data(&[("Cache", 10), ("logs", 10), ("Crashpad", 10)]);
        let plugin = VsCodePlugin::with_app_data(data.path());

        let scan = plugin.scan().expect("scan succeeds");
        let risk_of = |suffix: &str| {
            scan.targets
                .iter()
                .find(|t| t.path().ends_with(suffix))
                .unwrap_or_else(|| panic!("{suffix} target"))
                .risk
        };

        assert_eq!(risk_of("logs"), TargetRisk::Review);
        assert_eq!(risk_of("Crashpad"), TargetRisk::Review);
        assert_eq!(risk_of("Cache"), TargetRisk::Safe);
        assert!(!risk_of("logs").may_be_preselected());
    }

    #[test]
    fn a_missing_editor_reads_as_tool_unavailable() {
        let plugin = VsCodePlugin::with_app_data("/nonexistent/sentinel-test/Code");

        assert!(matches!(
            plugin.scan(),
            Err(PluginError::ToolUnavailable { .. })
        ));
    }

    #[test]
    fn an_editor_with_no_caches_yet_offers_nothing() {
        let data = fake_app_data(&[("User", 500)]);
        let plugin = VsCodePlugin::with_app_data(data.path());

        assert!(plugin.scan().expect("not an error").targets.is_empty());
    }

    #[test]
    fn recommendations_are_explanations_not_actions() {
        let data = fake_app_data(&[("Cache", 4096), ("logs", 10)]);
        let plugin = CursorPlugin::with_app_data(data.path());

        let recommendations = plugin.recommend().expect("recommend succeeds");

        assert_eq!(recommendations.len(), 2, "one per risk level present");
        for recommendation in &recommendations {
            assert!(!recommendation
                .detail
                .contains(data.path().to_string_lossy().as_ref()));
        }
    }

    #[test]
    fn estimate_matches_the_scan() {
        let data = fake_app_data(&[("Cache", 300), ("GPUCache", 200)]);
        let plugin = VsCodePlugin::with_app_data(data.path());

        let scan = plugin.scan().expect("scan succeeds");
        let estimate = plugin.estimate().expect("estimate succeeds");

        assert_eq!(estimate.reclaimable_bytes, scan.total_bytes());
        assert_eq!(estimate.target_count, scan.targets.len());
    }

    #[test]
    fn a_forged_target_is_refused() {
        let data = fake_app_data(&[("Cache", 10)]);
        let victim = tempfile::tempdir().expect("temp dir");
        fs::write(victim.path().join("settings.json"), "{}").expect("write");

        let plugin = VsCodePlugin::with_app_data(data.path());
        let forged = CleanTarget::new("vscode", victim.path(), "forged", 10, TargetRisk::Safe);

        let outcome = clean(&plugin, &[forged]).expect("refusal is reported, not fatal");

        assert!(outcome.removed.is_empty());
        assert!(victim.path().join("settings.json").exists());
    }

    /// One editor's target must not be cleanable through another's. They share
    /// a layout — pointed at the same directory the *paths* are identical, so
    /// the plugin id is the only thing standing between them. Every ordered
    /// pair is checked rather than one representative pair.
    #[test]
    fn one_editors_targets_are_refused_by_every_other() {
        let data = fake_app_data(&[("Cache", 10)]);

        for source in all_editors(data.path()) {
            let targets = source.scan().expect("scan succeeds").targets;

            for destination in all_editors(data.path()) {
                if destination.metadata().id == source.metadata().id {
                    continue;
                }

                let error = clean(destination.as_ref(), &targets).expect_err(&format!(
                    "a `{}` target must be refused by `{}`",
                    source.metadata().id,
                    destination.metadata().id
                ));

                assert!(matches!(error, PluginError::RejectedTarget { .. }));
            }
        }

        assert!(data.path().join("Cache").exists(), "nothing may be removed");
    }

    /// Reads this machine's real editor data, read-only. Ignored by default.
    #[test]
    #[ignore = "reads the developer's real editor data; run manually"]
    fn scans_the_real_editors() {
        for (name, scan) in [
            ("VS Code", VsCodePlugin::new().scan()),
            ("Cursor", CursorPlugin::new().scan()),
            ("Kiro", KiroPlugin::new().scan()),
            ("Antigravity", AntigravityPlugin::new().scan()),
        ] {
            println!("--- {name}");
            match scan {
                Ok(scan) => {
                    for target in &scan.targets {
                        println!(
                            "  {:>10}  {:?}  {}",
                            human_bytes(target.size_bytes),
                            target.risk,
                            target.path().display()
                        );
                    }
                    println!("  total: {}", human_bytes(scan.total_bytes()));
                }
                Err(PluginError::ToolUnavailable { detail }) => {
                    println!("  not installed here: {detail}");
                }
                Err(other) => panic!("unexpected scan failure: {other}"),
            }
        }
    }
}
